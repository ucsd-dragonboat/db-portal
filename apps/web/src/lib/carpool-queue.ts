// The auto-carpool job queue (migration 0040). When a form's due date passes, each
// of its days becomes a queued carpool_runs row; every cron tick then builds days
// one at a time until its time budget is spent, and the rest wait for the next tick.
// A tick killed mid-build leaves its job "running" — recover_stale_carpool_runs
// re-queues it later, so no day is ever lost.

import type { createAdminClient } from "@/lib/supabase/admin";
import { generateCarpoolForEvent, type GenerateResult } from "@/lib/carpool-auto";
import { RUN_MAX_ATTEMPTS, startRun, updateRun } from "@/lib/carpool-runs";
import { notifyCarpoolAutoGenerated } from "@/lib/notifications";

type AdminClient = ReturnType<typeof createAdminClient>;

/** Claims every past-due form and queues one job per linked day. */
export async function enqueueDueForms(supabase: AdminClient): Promise<{ enqueued: number; error?: string }> {
  const { data: due, error } = await supabase
    .from("forms")
    .select("id, org_id")
    .in("status", ["open", "closed"])
    .not("due_at", "is", null)
    .lt("due_at", new Date().toISOString())
    .is("carpools_generated_at", null);
  if (error) return { enqueued: 0, error: error.message };

  let enqueued = 0;
  for (const form of due ?? []) {
    // Claim before queueing so overlapping ticks can't queue a form twice.
    const { data: claimed } = await supabase
      .from("forms")
      .update({ carpools_generated_at: new Date().toISOString() })
      .eq("id", form.id)
      .is("carpools_generated_at", null)
      .select("id");
    if (!claimed?.length) continue;

    const { data: fes } = await supabase.from("form_events").select("event_id").eq("form_id", form.id).order("sort_order");
    for (const fe of fes ?? []) {
      const id = await startRun(supabase, { orgId: form.org_id, eventId: fe.event_id, trigger: "cron", status: "queued", formId: form.id });
      if (!id) {
        // Most likely migration 0040 hasn't run. Un-claim so the next tick tries again
        // (rows queued so far are dropped to avoid building those days twice).
        console.error("[cron] couldn't queue carpool jobs — has migration 0040 run?");
        await supabase.from("carpool_runs").delete().eq("form_id", form.id).eq("status", "queued");
        await supabase.from("forms").update({ carpools_generated_at: null }).eq("id", form.id);
        return { enqueued, error: "couldn't queue carpool jobs" };
      }
      enqueued++;
    }
  }
  return { enqueued };
}

export type QueueReport = { built: number; retried: number; recovered: number; left: number; results: Record<string, GenerateResult> };

/** Builds queued days, oldest first, until the queue is empty or budgetMs has passed. */
export async function processQueue(supabase: AdminClient, budgetMs: number, now: () => number = Date.now): Promise<QueueReport> {
  const start = now();
  const handled: string[] = [];
  const report: QueueReport = { built: 0, retried: 0, recovered: 0, left: 0, results: {} };
  const { data: recovered } = await supabase.rpc("recover_stale_carpool_runs", {});
  report.recovered = recovered ?? 0;

  while (now() - start < budgetMs) {
    const { data: claimed, error } = await supabase.rpc("claim_carpool_run", { p_skip: handled });
    if (error) { console.error("[cron] claim carpool job:", error.message); break; }
    const job = claimed?.[0];
    if (!job) break;
    handled.push(job.id);

    const result = await generateCarpoolForEvent(supabase, job.org_id, job.event_id, job.id);
    if ("error" in result && job.attempts < RUN_MAX_ATTEMPTS) {
      // Back of the queue; this tick won't claim it again (it's in `handled`).
      await updateRun(supabase, job.id, { status: "queued", detail: result.error });
      report.retried++;
      continue;
    }
    report.results[job.event_id] = result;
    report.built++;
    await notifyCarpoolAutoGenerated(job.org_id, job.event_id, result);
  }

  const { count } = await supabase.from("carpool_runs").select("id", { count: "exact", head: true }).eq("status", "queued").eq("trigger", "cron");
  report.left = count ?? 0;
  return report;
}
